import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";
import { projectRoot } from "../src/config.js";
import {
  advanceFashion,
  fashionProgress,
  fashionXp,
  fashionBody,
  fashionLevels,
} from "../src/features/fashion/index.js";
import { calculateAttributes } from "../src/attributes.js";
import { fashionAttributeSources } from "../src/features/attributes/fashion.js";
import { decodeMessage, typeName } from "../src/messages.js";

test("a tabela tipo 113 reproduz as 37 absorções reais, inclusive os saltos até 200", () => {
  const rows = readFileSync(
    join(projectRoot, "../../vendor/test-fixtures/backups/fashion-200-2026-10-12.jsonl.gz"),
  );
  // This independent fixture is the preserved online session, not generated by the implementation.
  const capture = JSON.parse(
    readFileSync(
      join(projectRoot, "../../vendor/test-fixtures/fashion-capture-verification-2026-10-12.json"),
      "utf8",
    ),
  );
  assert.equal(capture.upgradeResponses, 37);
  assert.ok(rows.length);
  const packets = gunzipSync(rows)
    .toString("utf8")
    .split("\n")
    .filter(Boolean)
    .map((s) => JSON.parse(s));
  const progress = fashionProgress();
  let observed = fashionProgress(),
    count = 0,
    checked = 0;
  for (const p of packets) {
    const body = Buffer.from(p.frame, "base64").subarray(20);
    if (p.opcode === 8594)
      count = decodeMessage(typeName("store.StoreReqMsg"), body).count;
    if (p.opcode === 301) observed = fashionProgress(body.toString("base64"));
    if (p.opcode === 4487) {
      const result = decodeMessage(typeName("store.StoreRspMsg"), body);
      const xp = fashionXp(result.compose_templateId) * count;
      assert.equal(xp, Number(result.$9.value));
      advanceFashion(progress, xp);
      assert.deepEqual(
        [progress.level, progress.xp],
        [observed.level, observed.xp],
      );
      checked++;
    }
  }
  assert.equal(checked, 37);
  assert.deepEqual([progress.level, progress.xp], [200, 0]);
  assert.equal(fashionLevels.size, 200);
  assert.throws(() => advanceFashion(progress, 200));
});
test("lotes e unidades têm a mesma progressão; os campos novos do protocolo são preservados", () => {
  const one = fashionProgress(),
    bulk = fashionProgress();
  for (let i = 0; i < 1000; i++) advanceFashion(one, 200);
  advanceFashion(bulk, 200000);
  assert.deepEqual(one, bulk);
  bulk.fields["19"] = 1;
  const encoded = fashionBody(bulk);
  const decoded = fashionProgress(encoded);
  assert.equal(decoded.fields["19"], 1);
  assert.equal(decoded.level, bulk.level);
  assert.equal(decoded.xp, bulk.xp);
  assert.throws(() => advanceFashion(one, -200));
});
test("bônus usam os skills do nível atual sem somar novamente níveis anteriores", () => {
  const hero = {
    total_phy_attack: 100,
    total_magic_attack: 100,
    total_phy_defence: 100,
    total_magic_defence: 100,
    total_live: 1000,
  };
  const state = { version: 1 as const, calculationVersion: 2 as const, sources: { ...fashionAttributeSources(200, {}), base: { kind: "natural" as const, evidence: "local-balance" as const, values: hero } } };
  const final = calculateAttributes(state);
  assert.equal(final.total_phy_attack, 4730);
  assert.equal(final.total_live, 47300);
  state.sources.base.values.total_phy_attack += 1000;
  assert.equal(calculateAttributes(state).total_phy_attack, 5830);
  assert.equal(fashionXp(208020), 200);
  assert.equal(fashionXp(208021), 200);
  assert.equal(fashionXp(1098303), 1600);
  assert.equal(fashionXp(1128064), 300);
});
